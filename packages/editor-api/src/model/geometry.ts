/** The values whose preset name is not the value with a lower-case first letter. */
const PRESETS: Readonly<Record<string, string>> = Object.assign(
  Object.create(null) as Record<string, string>,
  {
    LineInverse: 'lineInv',
    RightTriangle: 'rtTriangle',
    Rectangle: 'rect',
    RoundRectangle: 'roundRect',
    Round1Rectangle: 'round1Rect',
    Round2SameRectangle: 'round2SameRect',
    Round2DiagonalRectangle: 'round2DiagRect',
    SnipRoundRectangle: 'snipRoundRect',
    Snip1Rectangle: 'snip1Rect',
    Snip2SameRectangle: 'snip2SameRect',
    Snip2DiagonalRectangle: 'snip2DiagRect',
    DiagonalStripe: 'diagStripe',
    WedgeRRectCallout: 'wedgeRoundRectCallout',
  }
);

/** The ECMA-376 preset name of a geometric shape type, or `InvalidArgument` naming `target`. */
export function geometryOf(value: unknown, target: string): string {
  if (typeof value !== 'string' || !KNOWN.has(value))
    failArgument(target, oneOf([...KNOWN]), nearest(value, [...KNOWN]));
  return PRESETS[value] ?? value.charAt(0).toLowerCase() + value.slice(1);
}
